/**
 * POST /api/v1/aliases is the endpoint Bitwarden's addy.io forwarder calls:
 * it must accept Bitwarden's exact request, never store the plaintext
 * description, and surface error messages where Bitwarden reads them.
 */
import { describe, it, expect, vi, beforeEach, Mock } from 'vitest'
import { POST } from '@/app/api/v1/aliases/route'
import { AliasService } from '@/lib/services/alias'
import { validateApiKey, hasExplicitApiKey } from '@/lib/api-auth'
import { ValidationError } from '@/lib/api-error-utils'
import { personalScope } from '@/lib/ownership'

vi.mock('@/lib/services/alias', () => ({
  AliasService: {
    createAlias: vi.fn(),
  },
}))

vi.mock('@/lib/api-auth', () => ({
  validateApiKey: vi.fn(),
  hasExplicitApiKey: vi.fn(),
}))

// No session: keep the real better-auth instance (and its OAuth resource
// seeding against the database) out of this test.
vi.mock('@/auth', () => ({ auth: vi.fn().mockResolvedValue(null) }))

vi.mock('@/lib/prisma', () => ({
  prisma: {
    user: {
      findUnique: vi.fn().mockResolvedValue({
        banFileUpload: false,
        banAliasCreation: false,
      }),
    },
  },
}))

vi.mock('@/lib/api-rate-limit', () => ({
  createRateLimitHeaders: () => new Headers(),
}))

vi.mock('@/lib/rate-limit', () => ({
  rateLimit: vi.fn().mockResolvedValue(null),
  rateLimiters: {},
  getClientIp: vi.fn().mockResolvedValue('127.0.0.1'),
}))

// Mirrors CreateForwardingAddressRpc.toRequest in bitwarden/clients.
function bitwardenRequest(body: unknown) {
  return new Request('https://anon.li/api/v1/aliases', {
    method: 'POST',
    headers: {
      Authorization: 'Bearer ak_test',
      'Content-Type': 'application/json',
      Accept: 'application/json',
    },
    body: typeof body === 'string' ? body : JSON.stringify(body),
  })
}

describe('POST /api/v1/aliases (Bitwarden)', () => {
  beforeEach(() => {
    vi.clearAllMocks()
    ;(validateApiKey as unknown as Mock).mockResolvedValue({
      user: { id: 'user1', subscriptions: [] },
      rateLimit: { success: true, reset: new Date(), limit: 10, remaining: 9 },
      apiKeyId: 'key1',
      organizationId: null,
    })
    ;(hasExplicitApiKey as unknown as Mock).mockReturnValue(true)
    ;(AliasService.createAlias as unknown as Mock).mockResolvedValue({
      id: 'alias1',
      email: 'x7k9m2@anon.li',
      active: true,
      encryptedLabel: null,
      encryptedNote: null,
      createdAt: new Date('2026-10-25T00:00:00.000Z'),
      updatedAt: new Date('2026-10-25T00:00:00.000Z'),
    })
  })

  it('creates a random alias and returns it at data.email', async () => {
    const res = await POST(bitwardenRequest({
      domain: 'anon.li',
      description: 'Website: example.com. Generated by Bitwarden.',
    }))

    expect(res.status).toBe(201)
    const json = await res.json()
    expect(json.data.email).toBe('x7k9m2@anon.li')
  })

  it('drops the plaintext description instead of storing it', async () => {
    await POST(bitwardenRequest({
      domain: 'anon.li',
      description: 'Website: example.com. Generated by Bitwarden.',
    }))

    expect(AliasService.createAlias).toHaveBeenCalledWith(personalScope('user1'), {
      domain: 'anon.li',
      format: 'RANDOM',
    })
  })

  it('normalizes the free-form domain Bitwarden users type', async () => {
    await POST(bitwardenRequest({ domain: '  Anon.LI ', description: 'Generated by Bitwarden.' }))

    expect(AliasService.createAlias).toHaveBeenCalledWith(personalScope('user1'), {
      domain: 'anon.li',
      format: 'RANDOM',
    })
  })

  it('rejects malformed JSON', async () => {
    const res = await POST(bitwardenRequest('{not json'))

    expect(res.status).toBe(400)
    expect(AliasService.createAlias).not.toHaveBeenCalled()
  })

  it('puts the error message at the top level for an invalid API key', async () => {
    ;(validateApiKey as unknown as Mock).mockResolvedValue(null)

    const res = await POST(bitwardenRequest({ domain: 'anon.li' }))

    expect(res.status).toBe(401)
    expect(await res.json()).toEqual({ message: 'Unauthorized - API key required' })
  })

  it('puts service error messages at the top level', async () => {
    ;(AliasService.createAlias as unknown as Mock).mockRejectedValue(
      new ValidationError('Domain not available'),
    )

    const res = await POST(bitwardenRequest({ domain: 'example.com' }))

    expect(res.status).toBe(400)
    expect(await res.json()).toEqual({ message: 'Domain not available' })
    expect(res.headers.get('Content-Type')).toContain('application/json')
  })
})
